def bucket_of(name: str):
    """品名 → 桶名;查不到回 None(交給 LLM 臨場判斷或標記待審)。"""
    n = name.replace(" ", "")
    for b, kws in SYNONYMS.items():
        if any(kw in n for kw in kws):
            return b
    return None


def is_equity(name: str) -> bool:
    return any(k in name for k in EQUITY_KW)


def is_reconcile_only(name: str) -> bool:
    return any(k in name for k in RECONCILE_ONLY_KW)


def reconciles(bucket_sum: int, extra_sum: int, anchor: int) -> bool:
    """6. 對帳閘門:桶加總 + reconcile-only 加總 ≈ 錨。過→收,不過→N/A。"""
    if anchor is None:
        return False
    return abs(bucket_sum + extra_sum - anchor) <= max(RECON_ABS, RECON_REL * abs(anchor))
