"""保留集:**開發期間不准看的格子。**

為什麼需要:分桶表、同義詞、五道檢查的門檻,全都是看著已抄的格子長出來的。
看得越多,表越貼合那些格子 —— 而「貼合」與「通用」在只看訓練資料時**長得一模一樣**。
保留集就是唯一分得出這兩者的東西。

⚠️ **切的時機是現在,不是抄完之後。** 保留集必須是**還沒被看過**的格子;
已經抄過、已經拿來調過表的格子事後宣告為保留集,它只會給出樂觀的假答案。
本檔選的 3 格,截至 2026-07-26 一列都沒抄過、一頁都沒讀過。

⚠️ **一格只能用一次。** 用保留集調過表,它就變成訓練資料了,要另外再切。
真的動用時,把結果寫進 `docs/`,並在這裡標記作廢、換新的 3 格。

選格的理由(要涵蓋已知會出事的三種結構,不是隨機抽):
    202502_5843_AI3 OCI      兆豐半年報 —— 逐項成本 + 一整筆評價調整,
                             帳面在文件裡不存在。驗「該 null 時真的 null」
    202304_5847_AI3 Trading  玉山年報 Trading —— 附註含大量衍生,
                             驗三段恆等式與「衍生不進 7 桶」
    202502_5835_AI3 OCI      國泰半年報 —— 單一附註、無明細表,
                             驗第 3 道確實不適用而不是假裝通過
"""
HOLDOUT = {
    "202502_5843_AI3|OCI",
    "202304_5847_AI3|Trading",
    "202502_5835_AI3|OCI",
}


def split(cells):
    """{格: recs} → (訓練用, 保留集裡不小心混進來的)。"""
    leak = {k: v for k, v in cells.items() if k in HOLDOUT}
    return {k: v for k, v in cells.items() if k not in HOLDOUT}, leak
