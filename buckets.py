GENERIC = {"其他", "其他項目"}


def norm(s):
    """機械正規化:去空白、統一全半形括號。**零判斷**(plan_v3_2_flow.md §3 第 1 步)。

    PDF 抽出來的文字常常字間帶空格(「公 司 債」「其 他」),那是排版不是名稱差異。
    正規化只做這種一定不會錯的事;真正的名稱差異走 SYN(同義詞,判斷層)。
    """
    return (s.replace(" ", "").replace("　", "")
             .replace("（", "(").replace("）", ")"))


_SYN_N = {norm(k): v for k, v in SYN.items()}


def bucket(row):
    """rows 的一列 → 桶名,認不得回 None。

    通稱(「其他」)看所在段落;其餘一律看名字 —— 段落**不准覆蓋**具名科目,
    否則衍生段裡的「政府公債」會被整段吃掉。
    """
    n = norm(row["name"])
    if n in GENERIC:
        g = GROUP_SYN.get(norm(row.get("group") or ""))
        if g:
            return g
    return _SYN_N.get(n)


_PEND_N = {norm(k) for k in PENDING}


def pending(row):
    """這列是不是卡在人審佇列(≠ 單純沒收錄)。"""
    return norm(row["name"]) in _PEND_N


def is_adj(row):
    """這列是不是「評價調整」—— 成本橋到公允的差額,不是持有的資產。"""
    return bucket(row) == VALUATION_ADJ


def basis_of(rec):
    """由**表自己**判這份 record 的逐項口徑,回傳 "成本" 或 "公允"。

    ⚠️ **不讀 agent 宣告的 `rec["basis"]`。** 舊寫法是
    `if "成本" not in (rec.get("basis") or "")` —— 漏填就當公允放行,
    「偷懶 = 變綠」,跟 D1 恆真閘門同一種病。實測後果:中信 2023H1
    OCI_GB = 61,640,884 是成本卻被當帳面用,精準重現已發布的那個 bug。
    而且 `basis` 是自由敘述(兆豐 p125 一句話裡「取得成本」「公允價值」都有),
    散文沒法機械驗證,拿它對帳只會對出假警報 → **該欄位已停用,別再叫 agent 填。**

    判準是一行算術(見 memory/oracle-basis-mismatch):
        有評價調整列 → 逐項是【成本】,那列就是補到公允的差額
        沒有         → 逐項本身已是【公允】
    不看銀行、不看年報/半年報、不看附註或明細表、不看檔名。
    """
    return "成本" if any(is_adj(r) for r in rec["rows"]) else "公允"
